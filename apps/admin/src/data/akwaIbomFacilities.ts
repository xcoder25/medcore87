/**
 * Official list of Secondary Health Care Facilities in Akwa Ibom State
 * Source: Ministry of Health facility register
 *
 * Enrollment lifecycle:
 *   pending            → listed, no credentials yet
 *   credentials_issued → Commissioner (via M87) generated Hospi OS logins
 *   active             → facility used those logins / enrolled Hospi OS → streams live telemetry
 */

export type FacilityEnrollmentStatus = 'pending' | 'credentials_issued' | 'active';

export type FacilityTierLocal =
  | 'national_referral'
  | 'regional_general'
  | 'district_hospital'
  | 'cottage_hospital'
  | 'specialized_center'
  | 'comprehensive_health_centre';

export interface AkwaIbomFacility {
  facilityId: string;
  facilityName: string;
  location: string;
  region: string;
  tier: FacilityTierLocal;
  enrollmentStatus: FacilityEnrollmentStatus;
  /** Generated by Commissioner command via M87 */
  hospiLogin?: string;
  hospiTempPassword?: string;
  credentialsIssuedAt?: string;
  /** Set when facility first authenticates into Hospi OS */
  activatedAt?: string;
  lastSeenAt?: string;
  /** Live telemetry only when active */
  totalBeds?: number;
  occupiedBeds?: number;
  icuBedsTotal?: number;
  icuBedsOccupied?: number;
  ventilatorsAvailable?: number;
  staffOnDuty?: number;
  complianceScore?: number;
  emergencyStatus?: 'normal' | 'surge_code_yellow' | 'surge_code_red' | 'critical';
  licenseNumber?: string;
  licenseExpires?: string;
  accreditationStatus?: 'accredited' | 'provisional' | 'suspended' | 'pending';
}

function inferRegion(location: string, name: string): string {
  const t = `${location} ${name}`.toUpperCase();
  if (t.includes('UYO') || t.includes('ITU') || t.includes('IBESIT') || t.includes('NTO EDINO') || t.includes('MBIAYA'))
    return 'Uyo Region';
  if (t.includes('EKET') || t.includes('ORON') || t.includes('OKOBO') || t.includes('IBENO') || t.includes('EASTERN OBOLO') || t.includes('URUE-OFFONG') || t.includes('ORUKO'))
    return 'Eket Region';
  if (t.includes('IKOT EKPENE') || t.includes('ABAK') || t.includes('ESSEN') || t.includes('UKANA') || t.includes('IKPE') || t.includes('OBOT') || t.includes('EKPENE'))
    return 'Ikot Ekpene Region';
  if (t.includes('ORUK') || t.includes('ANAM') || t.includes('UKANA') || t.includes('IKOT ABASI') || t.includes('MKPAT') || t.includes('EASTERN'))
    return 'Oruk Anam Region';
  return 'Other Regions';
}

function inferTier(name: string): FacilityTierLocal {
  const t = name.toUpperCase();
  if (t.includes('PSYCHIATRIC') || t.includes('INFECTIOUS') || t.includes('LEPROSY')) return 'specialized_center';
  if (t.includes('COTTAGE')) return 'cottage_hospital';
  if (t.includes('COMPREHENSIVE')) return 'comprehensive_health_centre';
  if (t.includes('GENERAL') || t.includes('METHODIST') || t.includes('IMMANUEL') || t.includes('MARY SLESSOR') || t.includes('MOUNT CARMEL'))
    return 'district_hospital';
  return 'district_hospital';
}

