export function buildOfficialFacilityRegistry(): AkwaIbomFacility[] {
  return RAW_LIST.map((item, idx) => {
    const sn = idx + 1;
    const facilityId = `AKS-SEC-${String(sn).padStart(3, '0')}`;
    const displayName =
      item.name.includes('General Hospital') && item.name === 'General Hospital'
        ? `General Hospital, ${item.location}`
        : `${item.name}, ${item.location}`;

    return {
      facilityId,
      facilityName: displayName,
      location: item.location,
      region: inferRegion(item.location, item.name),
      tier: inferTier(item.name),
      enrollmentStatus: 'pending' as FacilityEnrollmentStatus,
      accreditationStatus: 'pending' as const,
    };
  });
}

/** Generate a one-time Hospi OS credential pair for a facility */
export function generateHospiCredentials(facility: AkwaIbomFacility): {
  hospiLogin: string;
  hospiTempPassword: string;
  issuedAt: string;
} {
  const slug = facility.location
    .replace(/[^a-zA-Z0-9]/g, '')
    .toUpperCase()
    .slice(0, 8);
  const rand = Math.random().toString(36).slice(2, 8).toUpperCase();
  const login = `HOSPI.${slug}.${facility.facilityId.slice(-3)}`;
  const password = `AKS-${rand}-${Date.now().toString(36).slice(-4).toUpperCase()}`;
  return {
    hospiLogin: login,
    hospiTempPassword: password,
    issuedAt: new Date().toISOString(),
  };
}

/** Simulate facility using the generated login → becomes active */
export function activateFacility(
  facility: AkwaIbomFacility
): AkwaIbomFacility {
  const beds = facility.tier === 'cottage_hospital' ? 40 + Math.floor(Math.random() * 40)
    : facility.tier === 'comprehensive_health_centre' ? 60 + Math.floor(Math.random() * 40)
    : facility.tier === 'specialized_center' ? 80 + Math.floor(Math.random() * 60)
    : 120 + Math.floor(Math.random() * 180);

  const occ = Math.floor(beds * (0.55 + Math.random() * 0.35));
  const icuTotal = Math.max(2, Math.floor(beds / 12));
  const icuOcc = Math.floor(icuTotal * (0.5 + Math.random() * 0.4));

  return {
    ...facility,
    enrollmentStatus: 'active',
    activatedAt: new Date().toISOString(),
    lastSeenAt: new Date().toISOString(),
    totalBeds: beds,
    occupiedBeds: occ,
    icuBedsTotal: icuTotal,
    icuBedsOccupied: icuOcc,
    ventilatorsAvailable: Math.floor(Math.random() * 6) + 1,
    staffOnDuty: Math.floor(beds * 0.35) + 20,
    complianceScore: Math.round((82 + Math.random() * 16) * 10) / 10,
    emergencyStatus: 'normal',
    licenseNumber: `MOH-LIC-2026-${facility.facilityId.slice(-3)}`,
    licenseExpires: '2028-12-31',
    accreditationStatus: 'provisional',
  };
}
